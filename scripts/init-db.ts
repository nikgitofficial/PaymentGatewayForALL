import { sql } from "../lib/db";

async function main() {
  await sql`
    CREATE TABLE IF NOT EXISTS leads (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      email text UNIQUE NOT NULL,
      verified boolean NOT NULL DEFAULT false,
      created_at timestamptz NOT NULL DEFAULT now()
    )`;
  await sql`
    CREATE TABLE IF NOT EXISTS invoices (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      lead_id uuid NOT NULL REFERENCES leads(id),
      items jsonb NOT NULL,
      total integer NOT NULL,
      status text NOT NULL DEFAULT 'pending',
      created_at timestamptz NOT NULL DEFAULT now()
    )`;
  await sql`
    CREATE TABLE IF NOT EXISTS payments (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      lead_id uuid NOT NULL REFERENCES leads(id),
      checkout_session_id text UNIQUE,
      amount integer NOT NULL,
      status text NOT NULL DEFAULT 'pending',
      paid_at timestamptz,
      created_at timestamptz NOT NULL DEFAULT now()
    )`;
  await sql`ALTER TABLE payments ADD COLUMN IF NOT EXISTS invoice_id uuid REFERENCES invoices(id)`;
  // Sequential invoice numbers (1, 2, 3 ...). Existing invoices are numbered automatically.
  await sql`ALTER TABLE invoices ADD COLUMN IF NOT EXISTS invoice_no integer GENERATED BY DEFAULT AS IDENTITY`;

  // Manual payments: the customer submits the GCash / bank reference, the owner confirms it.
  await sql`
    CREATE TABLE IF NOT EXISTS payment_claims (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      invoice_id uuid NOT NULL REFERENCES invoices(id),
      method text NOT NULL,
      reference text NOT NULL,
      sender_name text,
      status text NOT NULL DEFAULT 'pending',
      created_at timestamptz NOT NULL DEFAULT now(),
      reviewed_at timestamptz
    )`;
  // Amount the owner actually received (centavos), entered when confirming. For reconciliation.
  await sql`ALTER TABLE payment_claims ADD COLUMN IF NOT EXISTS amount_received integer`;
  // A reference can only be used once per method, so the same transfer can't pay two invoices.
  await sql`CREATE UNIQUE INDEX IF NOT EXISTS payment_claims_method_ref ON payment_claims (method, lower(reference))`;

  // Customer registration (/register): business details kept on the lead, used as "Bill to".
  // registered_at is set once a customer completes the form.
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS business_name text`;
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS contact_name text`;
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS phone text`;
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS address_line text`;
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS city text`;
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS state text`;
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS postal_code text`;
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS country text`;
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS tin text`;
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS registered_at timestamptz`;
  // Services the customer wants paid automatically (chosen on /register), plus optional notes.
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS services jsonb`;
  await sql`ALTER TABLE leads ADD COLUMN IF NOT EXISTS service_notes text`;
  console.log("Tables ready.");
}
main();
